// Google Maps needs its key baked into the merged manifest at build time, so it
// cannot come from --dart-define like the Dart-side config does. Read it from
// android/local.properties (git-ignored) and fall back to an empty string so a
// fresh clone still compiles — maps render as a blank grey tile until it's set.
val mapsApiKey: String = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}.getProperty("MAPS_API_KEY") ?: ""

